// The hub's frames are per profile, the battery belongs to each light, so
// the light draws the battery into the frame itself (README: "the light
// draws its own"). It composes the symbol from the pieces exported here –
// the label bitmaps and the charging bolt – so hub and light draw the same
// pixels, and the firmware's host tests compare its result with frames the
// hub rendered:
//
//	firmware/components/dm_core/src/dm_battery_font.h  pieces for dm_battery.c
//	firmware/test/host/battery_golden.h                frames to check it against
//
// go test ./internal/eink -run TestBatteryC -update rewrites both.
const (
	batteryFontC   = "../../../firmware/components/dm_core/src/dm_battery_font.h"
	batteryGoldenC = "../../../firmware/test/host/battery_golden.h"
	goldenRow0     = 180 // the golden frames keep only the footer
)

const generatedNote = "// Generated by hub/internal/eink (go test ./internal/eink -run TestBatteryC -update).\n// Do not edit – change the hub's footer and regenerate.\n"

// mask is a set of black pixels in whole bytes of the packed layout.
type mask struct {
	row0, rows, byte0, bytes int
	bits                     []byte // rows × bytes, 1 = set
}

func newMask(r image.Rectangle) mask {
	b0, b1 := r.Min.X/8, (r.Max.X-1)/8
	m := mask{row0: r.Min.Y, rows: r.Dy(), byte0: b0, bytes: b1 - b0 + 1}
	m.bits = make([]byte, m.rows*m.bytes)
	return m
}

func (m mask) set(x, y int) {
	m.bits[(y-m.row0)*m.bytes+x/8-m.byte0] |= 0x80 >> (x % 8)
}

// labelImage renders the label the way canvas.battery does, alone.
func labelImage(p int) *image.Paletted {
	c := newCanvas()
	defer c.close()
	f := c.face(regular, 13)
	x0, _, _, _ := batteryBox(footerBase)
	label := strconv.Itoa(p) + "%"
	c.text(f, x0-4-width(f, label), footerBase, label)
	return c.bw()
}

func blackBounds(p *image.Paletted) image.Rectangle {
	var r image.Rectangle
	for y := 0; y < Height; y++ {
		for x := 0; x < Width; x++ {
			if p.Pix[y*p.Stride+x] == 1 {
				r = r.Union(image.Rect(x, y, x+1, y+1))
			}
		}
	}
	return r
}

func cArray(b []byte, indent string) string {
	var s strings.Builder
	for i, v := range b {
		if i%16 == 0 {
			if i > 0 {
				s.WriteString("\n")
			}
			s.WriteString(indent)
		} else {
			s.WriteString(" ")
		}
		fmt.Fprintf(&s, "0x%02x,", v)
	}
	return s.String()
}

func batteryFontSource() []byte {
	labels := make([]*image.Paletted, 101)
	var box image.Rectangle
	for p := range labels {
		labels[p] = labelImage(p)
		box = box.Union(blackBounds(labels[p]))
	}
	var s bytes.Buffer
	s.WriteString(generatedNote)
	s.WriteString("// The battery in the footer of a 200 × 200 frame, as the hub draws it\n// (hub/internal/eink: footer, battery). Included by dm_battery.c only.\n#pragma once\n\n#include <stdint.h>\n\n")
	x0, y0, x1, y1 := batteryBox(footerBase)
	fmt.Fprintf(&s, "// The rule above the footer, from margin to margin.\n#define BAT_RULE_Y %d\n#define BAT_RULE_X0 %d\n#define BAT_RULE_X1 %d\n\n", footerTop, margin, Width-margin)
	fmt.Fprintf(&s, "// The symbol's body; the tip and the level follow from it.\n#define BAT_X0 %d\n#define BAT_Y0 %d\n#define BAT_X1 %d\n#define BAT_Y1 %d\n\n", x0, y0, x1, y1)

	lm := newMask(box)
	fmt.Fprintf(&s, "// \"0%%\" … \"100%%\", right-aligned left of the symbol: black pixels, rows\n// from BAT_LABEL_ROW0, bytes from BAT_LABEL_BYTE0 of each row.\n")
	fmt.Fprintf(&s, "#define BAT_LABEL_ROW0 %d\n#define BAT_LABEL_ROWS %d\n#define BAT_LABEL_BYTE0 %d\n#define BAT_LABEL_BYTES %d\n", lm.row0, lm.rows, lm.byte0, lm.bytes)
	s.WriteString("static const uint8_t bat_labels[101][BAT_LABEL_ROWS * BAT_LABEL_BYTES] = {\n")
	for p, img := range labels {
		m := newMask(box)
		for y := box.Min.Y; y < box.Max.Y; y++ {
			for x := box.Min.X; x < box.Max.X; x++ {
				if img.Pix[y*img.Stride+x] == 1 {
					m.set(x, y)
				}
			}
		}
		fmt.Fprintf(&s, "    // %d%%\n    {\n%s\n    },\n", p, cArray(m.bits, "        "))
	}
	s.WriteString("};\n\n")

	// The bolt: the pixels canvas.fill turns white.
	br := image.Rect(x0, y0-2, x1, y1+2)
	c := newCanvas()
	c.fill(br, func(float64, float64) bool { return true }, true)
	c.fill(br, batteryBolt(x0, y0), false)
	img := c.bw()
	c.close()
	bm := newMask(br)
	for y := br.Min.Y; y < br.Max.Y; y++ {
		for x := br.Min.X; x < br.Max.X; x++ {
			if img.Pix[y*img.Stride+x] == 0 {
				bm.set(x, y)
			}
		}
	}
	s.WriteString("// The charging bolt: pixels turned white over the level.\n")
	fmt.Fprintf(&s, "#define BAT_BOLT_ROW0 %d\n#define BAT_BOLT_ROWS %d\n#define BAT_BOLT_BYTE0 %d\n#define BAT_BOLT_BYTES %d\n", bm.row0, bm.rows, bm.byte0, bm.bytes)
	fmt.Fprintf(&s, "static const uint8_t bat_bolt[BAT_BOLT_ROWS * BAT_BOLT_BYTES] = {\n%s\n};\n", cArray(bm.bits, "    "))
	return s.Bytes()
}

func batteryGoldenSource() []byte {
	stamp := time.Date(2026, 10, 30, 14, 0, 0, 0, vienna)
	st := engine.State{Status: status.Working, Phase: status.PhaseNormal, Reason: engine.ReasonWorkHours, Since: now.Add(-time.Hour), Until: at(17, 0), Updated: now}
	cases := []struct {
		percent  int
		charging bool
		stamp    bool
	}{
		{0, false, true}, {1, false, true}, {5, true, true}, {42, false, true}, {42, true, true},
		{77, true, false}, {99, false, true}, {100, false, true}, {100, true, false},
	}
	footer := func(in Input) []byte {
		const stride = Width / 8
		return Pack(Render(in))[goldenRow0*stride:]
	}
	var s bytes.Buffer
	s.WriteString(generatedNote)
	fmt.Fprintf(&s, "// Footers (rows %d–%d) of frames the hub rendered without and with the\n// battery, for test_battery.c.\n#pragma once\n\n#include <stdbool.h>\n#include <stdint.h>\n\n", goldenRow0, Height-1)
	fmt.Fprintf(&s, "#define GOLDEN_ROW0 %d\n#define GOLDEN_BYTES %d\n\n", goldenRow0, (Height-goldenRow0)*Width/8)
	s.WriteString("static const struct {\n    int percent;\n    bool charging;\n    const uint8_t base[GOLDEN_BYTES];\n    const uint8_t want[GOLDEN_BYTES];\n} battery_golden[] = {\n")
	for _, tc := range cases {
		in := Input{State: st, Lang: "en"}
		if tc.stamp {
			in.Stamp = stamp
		}
		base := footer(in)
		in.Battery = &Battery{Percent: tc.percent, Charging: tc.charging}
		want := footer(in)
		fmt.Fprintf(&s, "    {\n        %d,\n        %t,\n        {\n%s\n        },\n        {\n%s\n        },\n    },\n",
			tc.percent, tc.charging, cArray(base, "            "), cArray(want, "            "))
	}
	s.WriteString("};\n")
	return s.Bytes()
}

func TestBatteryC(t *testing.T) {
	for path, src := range map[string][]byte{batteryFontC: batteryFontSource(), batteryGoldenC: batteryGoldenSource()} {
		if *update {
			if err := os.WriteFile(path, src, 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		got, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("%v (run go test ./internal/eink -run TestBatteryC -update)", err)
		}
		if !bytes.Equal(got, src) {
			t.Errorf("%s is out of date: the hub's footer changed – run go test ./internal/eink -run TestBatteryC -update and the firmware host tests", path)
		}
	}
}
